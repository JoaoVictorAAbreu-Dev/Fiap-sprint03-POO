CREATE TABLE TB_EQUIPE_MANUTENCAO (
    ID_EQUIPE NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100 CHAR) NOT NULL,
    ESPECIALIDADE VARCHAR2(100 CHAR) NOT NULL,
    ATIVA CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_EQUIPE PRIMARY KEY (ID_EQUIPE),
    CONSTRAINT UQ_EQUIPE_NOME UNIQUE (NOME),
    CONSTRAINT CK_EQUIPE_NOME CHECK (TRIM(NOME) IS NOT NULL),
    CONSTRAINT CK_EQUIPE_ESPECIALIDADE CHECK (TRIM(ESPECIALIDADE) IS NOT NULL),
    CONSTRAINT CK_EQUIPE_ATIVA CHECK (ATIVA IN ('S', 'N'))
);

CREATE TABLE TB_TRECHO_RODOVIA (
    ID_TRECHO NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    QUILOMETRO NUMBER(6, 0) NOT NULL,
    SENTIDO VARCHAR2(20 CHAR) NOT NULL,
    ALTURA_VEGETACAO_CM NUMBER(8, 2) NOT NULL,
    TIPO_CRESCIMENTO VARCHAR2(10 CHAR) NOT NULL,
    AREA_SENSIVEL CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    MONITORADO_IOT CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    CODIGO_SENSOR VARCHAR2(50 CHAR),
    CONSTRAINT PK_TRECHO PRIMARY KEY (ID_TRECHO),
    CONSTRAINT UQ_TRECHO_KM_SENTIDO UNIQUE (QUILOMETRO, SENTIDO),
    CONSTRAINT UQ_TRECHO_SENSOR UNIQUE (CODIGO_SENSOR),
    CONSTRAINT CK_TRECHO_KM CHECK (QUILOMETRO >= 0),
    CONSTRAINT CK_TRECHO_SENTIDO CHECK (TRIM(SENTIDO) IS NOT NULL),
    CONSTRAINT CK_TRECHO_ALTURA CHECK (ALTURA_VEGETACAO_CM >= 0),
    CONSTRAINT CK_TRECHO_TIPO CHECK (TIPO_CRESCIMENTO IN ('SECO', 'NORMAL', 'UMIDO')),
    CONSTRAINT CK_TRECHO_AREA CHECK (AREA_SENSIVEL IN ('S', 'N')),
    CONSTRAINT CK_TRECHO_IOT CHECK (MONITORADO_IOT IN ('S', 'N')),
    CONSTRAINT CK_TRECHO_SENSOR_IOT CHECK (
        (MONITORADO_IOT = 'S' AND TRIM(CODIGO_SENSOR) IS NOT NULL)
        OR (MONITORADO_IOT = 'N' AND CODIGO_SENSOR IS NULL)
    )
);

CREATE TABLE TB_RELATORIO_PRIORIDADE (
    ID_RELATORIO NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    DATA_GERACAO TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    QT_NORMAL NUMBER(10, 0) DEFAULT 0 NOT NULL,
    QT_BAIXA NUMBER(10, 0) DEFAULT 0 NOT NULL,
    QT_MEDIA NUMBER(10, 0) DEFAULT 0 NOT NULL,
    QT_ALTA NUMBER(10, 0) DEFAULT 0 NOT NULL,
    QT_CRITICA NUMBER(10, 0) DEFAULT 0 NOT NULL,
    RESUMO VARCHAR2(2000 CHAR) NOT NULL,
    CONSTRAINT PK_RELATORIO PRIMARY KEY (ID_RELATORIO),
    CONSTRAINT CK_RELATORIO_CONTAGENS CHECK (
        QT_NORMAL >= 0
        AND QT_BAIXA >= 0
        AND QT_MEDIA >= 0
        AND QT_ALTA >= 0
        AND QT_CRITICA >= 0
    ),
    CONSTRAINT CK_RELATORIO_RESUMO CHECK (TRIM(RESUMO) IS NOT NULL)
);

CREATE TABLE TB_INTERVENCAO_OPERACIONAL (
    ID_INTERVENCAO NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    ID_TRECHO NUMBER(19, 0) NOT NULL,
    ID_EQUIPE NUMBER(19, 0) NOT NULL,
    TIPO_INTERVENCAO VARCHAR2(30 CHAR) NOT NULL,
    NIVEL_PRIORIDADE VARCHAR2(10 CHAR) NOT NULL,
    ALTURA_PROJETADA_CM NUMBER(8, 2) NOT NULL,
    JUSTIFICATIVA VARCHAR2(1000 CHAR) NOT NULL,
    DATA_INTERVENCAO TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'PLANEJADA' NOT NULL,
    CONSTRAINT PK_INTERVENCAO PRIMARY KEY (ID_INTERVENCAO),
    CONSTRAINT FK_INTERV_TRECHO FOREIGN KEY (ID_TRECHO)
        REFERENCES TB_TRECHO_RODOVIA (ID_TRECHO),
    CONSTRAINT FK_INTERV_EQUIPE FOREIGN KEY (ID_EQUIPE)
        REFERENCES TB_EQUIPE_MANUTENCAO (ID_EQUIPE),
    CONSTRAINT CK_INTERV_TIPO CHECK (
        TIPO_INTERVENCAO IN (
            'SEM_INTERVENCAO',
            'ROCADA_MANUAL',
            'ROCADA_MECANIZADA',
            'PULVERIZACAO'
        )
    ),
    CONSTRAINT CK_INTERV_PRIORIDADE CHECK (
        NIVEL_PRIORIDADE IN ('NORMAL', 'BAIXA', 'MEDIA', 'ALTA', 'CRITICA')
    ),
    CONSTRAINT CK_INTERV_ALTURA CHECK (ALTURA_PROJETADA_CM >= 0),
    CONSTRAINT CK_INTERV_JUSTIFICATIVA CHECK (TRIM(JUSTIFICATIVA) IS NOT NULL),
    CONSTRAINT CK_INTERV_STATUS CHECK (
        STATUS IN ('PLANEJADA', 'EM_ANDAMENTO', 'CONCLUIDA', 'CANCELADA')
    )
);

CREATE INDEX IX_INTERV_TRECHO_DATA
    ON TB_INTERVENCAO_OPERACIONAL (ID_TRECHO, DATA_INTERVENCAO);

CREATE INDEX IX_INTERV_EQUIPE_DATA
    ON TB_INTERVENCAO_OPERACIONAL (ID_EQUIPE, DATA_INTERVENCAO);

CREATE INDEX IX_RELATORIO_DATA
    ON TB_RELATORIO_PRIORIDADE (DATA_GERACAO, ID_RELATORIO);
