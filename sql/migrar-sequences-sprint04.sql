-- Execute uma vez no schema Oracle existente da Sprint 03, antes de subir a API.
-- Preserva as tabelas, os dados, as FKs e os IDENTITYs legados.
-- O intervalo a partir de 1000000000 fica reservado aos IDs gerados pelo JPA.
-- Pare as escritas no schema durante a migracao.
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

DECLARE
    v_maior NUMBER;
BEGIN
    SELECT GREATEST(
        NVL((SELECT MAX(ID_EQUIPE) FROM TB_EQUIPE_MANUTENCAO), 0),
        NVL((SELECT MAX(ID_TRECHO) FROM TB_TRECHO_RODOVIA), 0),
        NVL((SELECT MAX(ID_RELATORIO) FROM TB_RELATORIO_PRIORIDADE), 0),
        NVL((SELECT MAX(ID_INTERVENCAO) FROM TB_INTERVENCAO_OPERACIONAL), 0)
    ) INTO v_maior FROM DUAL;

    IF v_maior >= 1000000000 THEN
        RAISE_APPLICATION_ERROR(-20001, 'ID existente na faixa reservada ao JPA; revise a migracao antes de continuar.');
    END IF;
END;
/

CREATE SEQUENCE SEQ_EQUIPE_MANUTENCAO START WITH 1000000000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_TRECHO_RODOVIA START WITH 1000000000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_RELATORIO_PRIORIDADE START WITH 1000000000 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_INTERVENCAO_OPERACIONAL START WITH 1000000000 INCREMENT BY 1 NOCACHE NOCYCLE;
